export function NodeIcon({ node }: { node: SceneNode }) {
  switch (iconOf(node)) {
    case 'image':
      return <ImageIcon />
    case 'text':
      return <TextIcon />
    case 'camera':
      return <CameraIcon />
    default:
      return <FolderIcon />
  }
}
